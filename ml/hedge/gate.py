"""The gate model: P(acting on this ticket is right), and its export to the Forge app.

An L2-regularized logistic regression fit on standardized features. The standardization is
folded back into raw-feature weights before export, so the JavaScript gate only computes
sigmoid(bias + sum of weight * feature) and needs no scaler.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy.optimize import minimize
from scipy.special import expit

from .features import FEATURE_SCHEMA
from .risk import Threshold


@dataclass(frozen=True)
class GateModel:
    names: tuple[str, ...]
    weights: np.ndarray  # on raw features
    bias: float

    def predict_proba(self, X: np.ndarray) -> np.ndarray:
        return expit(np.asarray(X, dtype=float) @ self.weights + self.bias)


def fit_gate(X, y, names, l2: float = 1.0) -> GateModel:
    """Fit on features X (n, d) and labels y (1 = acting would be right).

    The objective is mean log loss + l2 / (2n) * ||w||^2 on standardized weights: a Gaussian
    prior with fixed precision l2. Its pull fades as n grows, so on millions of rows l2 = 1
    barely regularizes; raise it if the gate overfits. The bias is not penalized.
    """
    X = np.asarray(X, dtype=float)
    y = np.asarray(y, dtype=float)
    if X.ndim != 2 or X.shape[0] != y.size or X.shape[1] != len(names):
        raise ValueError("X must be (n, len(names)) and y must have n labels")
    if not np.all(np.isfinite(X)):
        raise ValueError("features must be finite")
    if not set(np.unique(y)) <= {0.0, 1.0}:
        raise ValueError("labels must be 0 or 1")
    mu = X.mean(axis=0)
    sd = X.std(axis=0)
    sd[sd == 0] = 1.0  # a constant feature gets weight 0 from the penalty anyway
    Z = (X - mu) / sd
    n, d = Z.shape

    def loss(theta):
        w, b = theta[:d], theta[d]
        z = Z @ w + b
        # log(1 + e^z) - y z, computed stably
        nll = np.logaddexp(0, z) - y * z
        p = expit(z)
        grad_w = Z.T @ (p - y) / n + l2 / n * w
        grad_b = np.mean(p - y)
        return nll.mean() + l2 / (2 * n) * w @ w, np.append(grad_w, grad_b)

    res = minimize(loss, np.zeros(d + 1), jac=True, method="L-BFGS-B")
    if not res.success:
        raise RuntimeError(f"gate fit did not converge: {res.message}")
    w_std, b_std = res.x[:d], res.x[d]
    weights = w_std / sd
    bias = float(b_std - (mu / sd) @ w_std)
    return GateModel(tuple(names), weights, bias)


def policy_dict(
    model: GateModel,
    threshold: Threshold,
    alpha: float,
    delta: float,
    calibration_size: int,
    retriever: str,
) -> dict:
    """The policy object the Forge gate reads. An uncertified threshold keeps the gate closed.

    ``retriever`` names the retriever whose scores the gate was trained on (for example
    "bm25-v1"). Scores from a different retriever have a different scale, so the Forge gate
    refuses to act when its retriever id or feature schema differs from the policy's.
    """
    if not retriever:
        raise ValueError("retriever id is required")
    calibrated = bool(np.isfinite(threshold.threshold))
    return {
        "calibrated": calibrated,
        "featureSchema": FEATURE_SCHEMA,
        "retriever": retriever,
        "alpha": alpha,
        "delta": delta,
        "calibrationSize": int(calibration_size),
        "threshold": float(threshold.threshold) if calibrated else None,
        "calibrationCoverage": threshold.coverage,
        "calibrationActed": threshold.acted,
        "calibrationErrors": threshold.errors,
        "model": {
            "bias": model.bias,
            "weights": {name: float(w) for name, w in zip(model.names, model.weights)},
        },
    }


def write_policy(policy: dict, path: str | Path) -> Path:
    """Write one policy as an ES module the Forge bundler can import."""
    return _write_module(policy, path)


def write_policies(policies: dict[str, dict], path: str | Path) -> Path:
    """Write one policy per action as the module app/src/policy.js exports: {link, clear}.

    Each policy must name the action it is keyed under, since the Forge gate refuses a
    policy certified for one action when it is asked about another.
    """
    for action, policy in policies.items():
        if policy.get("action") != action:
            raise ValueError(f"policy under {action!r} was certified for {policy.get('action')!r}")
    return _write_module(policies, path)


def _write_module(value, path: str | Path) -> Path:
    path = Path(path)
    body = json.dumps(value, indent=2, allow_nan=False)
    path.write_text(
        "// Generated by ml/hedge/gate.py. Do not edit by hand.\n"
        f"export default {body};\n"
    )
    return path
