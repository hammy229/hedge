"""Export a run of real public Jira issues as the app's sample data.

A judge's site starts empty, and Hedge asks about every ticket in a project with fewer
than 30 earlier issues (ADR 8). The admin page's seeder creates these issues in order so a
judge sees Hedge act, and sees it ask about real duplicates.

The span is picked by a rule fixed before looking at what the gate does with it: the
latest ``size`` consecutive issues of one project (by creation time) in which at least
``min_duplicates`` issues duplicate an earlier issue of the same span.

    python -m hedge.seed ../data/issues.jsonl.gz --jira Jira --project JSWSERVER \\
        --size 150 --min-duplicates 4 --out ../app/src/seed.js

The issues come from the Public Jira Dataset (Montgomery, Lüders and Maalej, MSR 2022),
licensed CC BY 4.0. The module keeps each issue's original key for attribution.
"""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from pathlib import Path

from .corpus import MAX_DESCRIPTION
from .leakage import DUPLICATE_PHRASE, ISSUE_URL, _strip_keys

ATTRIBUTION = (
    "Issues from the Public Jira Dataset: Montgomery, Lüders and Maalej, \"An Alternative Issue "
    "Tracking Dataset of Public Jira Repositories\", MSR 2022, https://doi.org/10.5281/zenodo.5901804. "
    "CC BY 4.0. Issue keys, links and 'duplicate of' phrases are removed; descriptions are cut to "
    f"{MAX_DESCRIPTION} characters."
)


def _key(r: dict) -> str:
    return r["id"].split(":", 1)[-1] if "id" in r else r["key"]


def _earlier_duplicates(span: list[dict]) -> list[list[int]]:
    pos = {_key(r): i for i, r in enumerate(span)}
    out = []
    for i, r in enumerate(span):
        hits = {pos[k] for d in r.get("duplicates", []) if (k := d.split(":", 1)[-1]) in pos and pos[k] < i}
        out.append(sorted(hits))
    return out


def pick_span(issues: list[dict], size: int, min_duplicates: int) -> list[dict]:
    """The latest ``size`` consecutive issues holding ``min_duplicates`` in-span duplicates."""
    ordered = sorted(issues, key=lambda r: (r["created"], _key(r)))
    for start in range(len(ordered) - size, -1, -1):
        span = ordered[start : start + size]
        if sum(1 for d in _earlier_duplicates(span) if d) >= min_duplicates:
            return span
    raise ValueError(f"no span of {size} issues has {min_duplicates} in-span duplicates")


def scrub(text: str, project_keys) -> str:
    """Drop issue links, issue keys and 'duplicate of' phrases; keep line breaks.

    The keys point at issues that do not exist on a judge's site, and a phrase like
    "duplicate of" would hand the answer to the retriever. Calibration text had the same
    things stripped (``leakage.strip_answer_text``).
    """
    text = ISSUE_URL.sub(" ", text or "")
    text = _strip_keys(text, project_keys)
    return DUPLICATE_PHRASE.sub(" ", text)


def seed_records(span: list[dict]) -> list[dict]:
    projects = sorted({r["project"] for r in span})
    dupes = _earlier_duplicates(span)
    return [
        {
            "source": _key(r),
            "summary": scrub(r.get("summary") or "", projects).strip(),
            "description": scrub((r.get("description") or "")[:MAX_DESCRIPTION], projects),
            "duplicateOf": d,
        }
        for r, d in zip(span, dupes)
    ]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("issues", type=Path, help="issues.jsonl.gz written by hedge.extract")
    ap.add_argument("--jira", required=True)
    ap.add_argument("--project", required=True)
    ap.add_argument("--size", type=int, default=150)
    ap.add_argument("--min-duplicates", type=int, default=4)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    issues = []
    with gzip.open(args.issues, "rt") as f:
        for line in f:
            r = json.loads(line)
            if r["jira"] == args.jira and r["project"] == args.project and r.get("created") is not None:
                issues.append(r)
    span = pick_span(issues, args.size, args.min_duplicates)
    body = {
        "attribution": ATTRIBUTION,
        "source": {"jira": args.jira, "project": args.project, "first": _key(span[0]), "last": _key(span[-1])},
        "issues": seed_records(span),
    }
    args.out.write_text(
        "// Generated by ml/hedge/seed.py. Do not edit by hand.\n"
        f"// {ATTRIBUTION}\n"
        f"export default {json.dumps(body, indent=2, ensure_ascii=False)};\n"
    )
    print(f"{args.project}: {body['source']['first']} to {body['source']['last']}, "
          f"{sum(1 for r in body['issues'] if r['duplicateOf'])} in-span duplicates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
